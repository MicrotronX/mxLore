#!/bin/bash
# Build mxLore release ZIP
# Usage: bash build-release.sh [version]
# Example: bash build-release.sh 2.2.1

VERSION=${1:-"2.4.0"}
BASENAME="mxLore-v${VERSION}-win64"
OUTDIR="release/${BASENAME}"
ZIPFILE="release/${BASENAME}.zip"
SRCDIR="$(cd "$(dirname "$0")" && pwd)"

echo "Building ${BASENAME}..."

# Pre-release gate (ADR-12216): no temporary probes, no orchestrator secrets in the index
ORCH="${SRCDIR}/src/orchestrator-go"
if grep -q "mouse-probe" "${ORCH}"/*.go; then
  echo "GATE FAILED: temporary mouse-probe still in src/orchestrator-go"; exit 1
fi
LEAK=$(git -C "${SRCDIR}" ls-files src/orchestrator-go | grep -E '\.pem$|orchestrator\.json$|setup-code\.txt$|sessions\.json$')
if [ -n "${LEAK}" ]; then
  echo "GATE FAILED: private orchestrator files are tracked:"; echo "${LEAK}"; exit 1
fi

# Orchestrator: release builds only via build.sh (-trimpath, no local paths in the EXE)
ORCH_EXE="${SRCDIR}/release/orchestrator-build/mxLoreOrchestrator.exe"
bash "${ORCH}/build.sh" "${ORCH_EXE}" || { echo "Orchestrator build failed (Go on PATH?)"; exit 1; }

# Clean
rm -rf "release/${BASENAME}" "${ZIPFILE}"
mkdir -p "${OUTDIR}/sql" "${OUTDIR}/admin/www/js" "${OUTDIR}/admin/www/js/lib" "${OUTDIR}/admin/www/css" "${OUTDIR}/lib" "${OUTDIR}/claude-setup/proxy"

# Server EXEs
cp "${SRCDIR}/mxLoreMCP.exe"     "${OUTDIR}/"
cp "${SRCDIR}/mxLoreMCPGui.exe"  "${OUTDIR}/"

# Proxy
cp "${SRCDIR}/claude-setup/proxy/mxMCPProxy.exe" "${OUTDIR}/"

# Orchestrator (browser terminal tabs for Claude Code)
mkdir -p "${OUTDIR}/orchestrator" || { echo "ERROR: cannot create ${OUTDIR}/orchestrator"; exit 1; }
cp "${ORCH_EXE}"                         "${OUTDIR}/orchestrator/" || { echo "ERROR: copy failed: ${ORCH_EXE}"; exit 1; }
# Microsoft ConPTY (MIT) must sit next to the EXE, else Windows' built-in ConPTY drops OSC 7501
cp "${ORCH}/bin/conpty.dll"               "${OUTDIR}/orchestrator/" || { echo "ERROR: copy failed: bin/conpty.dll"; exit 1; }
cp "${ORCH}/bin/OpenConsole.exe"          "${OUTDIR}/orchestrator/" || { echo "ERROR: copy failed: bin/OpenConsole.exe"; exit 1; }
cp "${ORCH}/THIRD-PARTY-NOTICES.txt"      "${OUTDIR}/orchestrator/" || { echo "ERROR: copy failed: THIRD-PARTY-NOTICES.txt"; exit 1; }
cp "${ORCH}/README.md"                    "${OUTDIR}/orchestrator/" || { echo "ERROR: copy failed: README.md"; exit 1; }

# Config
cp "${SRCDIR}/mxLoreMCP.ini.example" "${OUTDIR}/"

# SQL — setup.sql is the fresh-install base; numbered 0NN-*.sql files are
# picked up at boot by the auto-migrate pass for upgrade deployments.
cp "${SRCDIR}/sql/setup.sql" "${OUTDIR}/sql/"
cp "${SRCDIR}"/sql/0[0-9][0-9]-*.sql "${OUTDIR}/sql/"

# Admin UI
cp "${SRCDIR}/admin/www/index.html"        "${OUTDIR}/admin/www/"
cp "${SRCDIR}/admin/www/connect.html"      "${OUTDIR}/admin/www/"
cp "${SRCDIR}/admin/www/favicon.svg"       "${OUTDIR}/admin/www/"
# CSS + JS: glob all files, never hand-enumerate. A per-file list silently
# drops newly added assets (e.g. acl-helper.js) and ships a broken Admin-UI.
cp "${SRCDIR}"/admin/www/css/*.css "${OUTDIR}/admin/www/css/"
cp "${SRCDIR}"/admin/www/js/*.js   "${OUTDIR}/admin/www/js/"
# Vendored frontend libs (three.js, OrbitControls) live in js/lib/ — the
# js/*.js glob above does NOT recurse, so they must be copied explicitly or
# the 3D Knowledge Graph breaks in distributed builds (Spec#7677).
cp "${SRCDIR}"/admin/www/js/lib/*.js "${OUTDIR}/admin/www/js/lib/"

# claude-setup (skills, hooks, reference — served by mx_onboard_developer)
cp -r "${SRCDIR}/claude-setup/skills" "${OUTDIR}/claude-setup/skills"
cp -r "${SRCDIR}/claude-setup/hooks" "${OUTDIR}/claude-setup/hooks"
cp -r "${SRCDIR}/claude-setup/commands" "${OUTDIR}/claude-setup/commands"
cp -r "${SRCDIR}/claude-setup/reference" "${OUTDIR}/claude-setup/reference"
# mxMCPProxy.ini is auto-generated by the EXE on first run (embedded template in mx.Proxy.Config.pas).
cp "${SRCDIR}/claude-setup/CLAUDE.md" "${OUTDIR}/claude-setup/CLAUDE.md"
# Remove any EXEs that slipped in
find "${OUTDIR}/claude-setup" -name "*.exe" -delete 2>/dev/null

# Docs
cp "${SRCDIR}/LICENSE.txt" "${OUTDIR}/"
cp "${SRCDIR}/README.md"   "${OUTDIR}/"
mkdir -p "${OUTDIR}/docs"
cp "${SRCDIR}/docs/installation.md"    "${OUTDIR}/docs/"
cp "${SRCDIR}/docs/troubleshooting.md" "${OUTDIR}/docs/"
cp "${SRCDIR}/docs/team-onboarding.md" "${OUTDIR}/docs/"

# IIS reverse proxy config (optional, for WAN deployments)
cp "${SRCDIR}/iis-url-rewrite-rule.xml" "${OUTDIR}/"

# Note: libmariadb32.dll is NOT bundled (LGPL).
# The server auto-detects it from your MariaDB installation.
# If auto-detection fails, copy lib/libmariadb32.dll from your MariaDB to lib/.

echo ""
echo "Release directory: ${OUTDIR}"
echo ""
echo "Contents:"
find "${OUTDIR}" -type f | sort | while read f; do
  size=$(stat -c%s "$f" 2>/dev/null || stat -f%z "$f" 2>/dev/null)
  echo "  $(echo "$f" | sed "s|${OUTDIR}/||")  (${size} bytes)"
done

# Create ZIP
SEVENZIP="${SEVENZIP:-$(command -v 7z 2>/dev/null || echo '/c/Program Files/7-Zip/7z.exe')}"
if [ -x "$SEVENZIP" ] || command -v 7z &>/dev/null; then
  cd release && "$SEVENZIP" a -tzip "../${ZIPFILE}" "${BASENAME}" && cd ..
  echo ""
  echo "ZIP created: ${ZIPFILE}"
elif command -v zip &>/dev/null; then
  cd release && zip -r "../${ZIPFILE}" "${BASENAME}" && cd ..
  echo ""
  echo "ZIP created: ${ZIPFILE}"
else
  echo ""
  echo "No zip tool found. Manual ZIP: compress release/${BASENAME}/"
  echo "Tools: 7z, zip, or Windows Explorer right-click > Send to > Compressed folder"
fi

echo ""
echo "Done. Test the release on a clean machine with:"
echo "  1. Extract ZIP"
echo "  2. Copy mxLoreMCP.ini.example -> mxLoreMCP.ini"
echo "  3. Set Password= in INI"
echo "  4. Run mxLoreMCP.exe"
echo "  5. Open http://localhost:8081"
